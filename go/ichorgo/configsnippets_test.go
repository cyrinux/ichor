// snippetRuntime validates without an install disk (the generated configs have none).
type snippetRuntime struct{}

func (snippetRuntime) String() string        { return "container" }
func (snippetRuntime) RequiresInstall() bool { return false }
func (snippetRuntime) InContainer() bool     { return true }

// legacyDraft is a v1alpha1-only config, as clusters made before Talos 1.12 have.
const legacyDraft = `version: v1alpha1
machine:
    type: controlplane
    token: '******'
    ca:
        crt: '******'
    network:
        hostname: cp-1
        interfaces:
            - interface: eth1
              dhcp: true
cluster:
    controlPlane:
        endpoint: https://192.0.2.10:6443
    clusterName: test
`

// modernDraft is a config generated by Talos 1.14 machinery: settings in their own documents.
func modernDraft(t *testing.T, role machine.Type) string {
	t.Helper()

	in, err := generate.NewInput("test", "https://192.0.2.10:6443", "1.34.0")
	if err != nil {
		t.Fatal(err)
	}

	cfg, err := in.Config(role)
	if err != nil {
		t.Fatal(err)
	}

	text, err := cfg.EncodeString(encoder.WithComments(encoder.CommentsDisabled))
	if err != nil {
		t.Fatal(err)
	}

	return text
}

// applySnippet applies the edits of a snippet result to draft, each with MachineConfigEdit.
func applySnippet(t *testing.T, draft, out string, err error) (string, snippetResult) {
	t.Helper()

	r := decodeJSON[snippetResult](t, out, err)

	for _, e := range r.Edits {
		edit, err := json.Marshal(e)
		if err != nil {
			t.Fatal(err)
		}

		if draft, err = MachineConfigEdit(draft, string(edit)); err != nil {
			t.Fatalf("edit %+v: %v", e, err)
		}
	}

	return draft, r
}

var snippetCases = []struct {
	id     string
	params map[string]string
	// want: text the edited legacy and modern drafts must hold.
	legacy, modern string
}{
	{"ntp", map[string]string{"servers": "a.example.test, b.example.test"}, "servers:\n            - a.example.test", "servers:\n            - a.example.test"},
	{"dns", map[string]string{"nameservers": "192.0.2.53\n192.0.2.54"}, "nameservers:\n            - 192.0.2.53", "- address: 192.0.2.53"},
	{"mtu", map[string]string{"interface": "eth1", "mtu": "9000"}, "mtu: 9000", "mtu: 9000"},
	{"sysctl", map[string]string{"key": "net.core.somaxconn", "value": "65535"}, "net.core.somaxconn: \"65535\"", "net.core.somaxconn: \"65535\""},
	{"kernel_args", map[string]string{"args": "console=ttyS0"}, "- console=ttyS0", "- console=ttyS0"},
	{"kubelet_arg", map[string]string{"key": "max-pods", "value": "250"}, "max-pods: \"250\"", "max-pods: \"250\""},
	{"apiserver_arg", map[string]string{"key": "audit-log-maxage", "value": "30"}, "audit-log-maxage: \"30\"", "audit-log-maxage: \"30\""},
	{"node_label", map[string]string{"key": "example.test/rack", "value": "r1"}, "example.test/rack: r1", "example.test/rack: r1"},
	{"registry_mirror", map[string]string{"host": "docker.io", "endpoint": "https://mirror.example.test"}, "- https://mirror.example.test", "- https://mirror.example.test"},
	{"kubespan", map[string]string{"enabled": "true"}, "kubespan:\n            enabled: true", "kubespan:\n            enabled: true"},
}

func TestEverySnippetMakesAValidConfig(t *testing.T) {
	list, err := ConfigSnippets()
	listed := decodeJSON[struct{ Snippets []configSnippet }](t, list, err)
	if len(listed.Snippets) != len(snippetCases) {
		t.Fatalf("snippets = %d, cases = %d", len(listed.Snippets), len(snippetCases))
	}

	modern := modernDraft(t, machine.TypeControlPlane)

	for _, tc := range snippetCases {
		params, _ := json.Marshal(tc.params) //nolint:errcheck

		for _, draft := range []struct{ name, text, want string }{{"legacy", legacyDraft, tc.legacy}, {"modern", modern, tc.modern}} {
			t.Run(tc.id+"/"+draft.name, func(t *testing.T) {
				out, err := ConfigSnippetEdits(draft.text, tc.id, string(params))
				edited, r := applySnippet(t, draft.text, out, err)

				if !strings.Contains(edited, draft.want) {
					t.Errorf("no %q in\n%s", draft.want, edited)
				}

				if r.Staged != (tc.id == "kernel_args") {
					t.Errorf("staged = %v", r.Staged)
				}

				if draft.name == "modern" {
					// The modern config is complete: Talos' own validation must accept it.
					provider, err := configloader.NewFromBytes([]byte(edited))
					if err != nil {
						t.Fatal(err)
					}

					if _, err := provider.ValidateAsClient(snippetRuntime{}); err != nil {
						t.Errorf("invalid config: %v", err)
					}
				}
			})
		}
	}
}

func TestSnippetsUseTheDocumentsOfTheDraft(t *testing.T) {
	modern := modernDraft(t, machine.TypeControlPlane)

	// DNS goes to the ResolverConfig document: Talos refuses v1alpha1 nameservers next to it.
	out, err := ConfigSnippetEdits(modern, "dns", `{"nameservers":"192.0.2.53"}`)
	r := decodeJSON[snippetResult](t, out, err)

	docs, _ := parseConfigDocs(modern) //nolint:errcheck
	if e := r.Edits[0]; configDocKind(docs[e.Doc]) != "ResolverConfig" || strings.Join(e.Path, ".") != "nameservers" {
		t.Errorf("dns edit = %+v", e)
	}

	// NTP goes to a TimeSyncConfig document when there is one, and Talos accepts the result.
	withTimeSync := modern + "---\napiVersion: v1alpha1\nkind: TimeSyncConfig\nntp:\n    servers:\n        - old.example.test\n"
	out, err = ConfigSnippetEdits(withTimeSync, "ntp", `{"servers":"a.example.test"}`)
	edited, _ := applySnippet(t, withTimeSync, out, err)

	if !strings.Contains(edited, "kind: TimeSyncConfig\nntp:\n    servers:\n        - a.example.test") || strings.Contains(edited, "old.example.test") {
		t.Errorf("time sync:\n%s", edited)
	}

	provider, err := configloader.NewFromBytes([]byte(edited))
	if err != nil {
		t.Fatal(err)
	}

	if _, err := provider.ValidateAsClient(snippetRuntime{}); err != nil {
		t.Errorf("invalid config: %v", err)
	}

	// The legacy config has no such document: the v1alpha1 field.
	out, err = ConfigSnippetEdits(legacyDraft, "kubelet_arg", `{"key":"max-pods","value":"250"}`)
	r = decodeJSON[snippetResult](t, out, err)

	if e := r.Edits[0]; e.Doc != 0 || strings.Join(e.Path, ".") != "machine.kubelet.extraArgs.max-pods" {
		t.Errorf("kubelet edit = %+v", e)
	}
}

func TestSnippetRefusals(t *testing.T) {
	worker := strings.Replace(legacyDraft, "type: controlplane", "type: worker", 1)

	for _, tc := range []struct{ draft, id, params, want string }{
		{legacyDraft, "nope", `{}`, "unknown snippet"},
		{legacyDraft, "ntp", `{"servers":" , "}`, "servers is missing"},
		{legacyDraft, "mtu", `{"interface":"eth0","mtu":"big"}`, "not a positive whole number"},
		{legacyDraft, "kubespan", `{"enabled":"yes"}`, "not true or false"},
		{legacyDraft, "registry_mirror", `{"host":"docker.io","endpoint":"mirror.example.test"}`, "not a URL"},
		{worker, "apiserver_arg", `{"key":"a","value":"b"}`, "only a control plane"},
		{"key: [", "ntp", `{"servers":"a"}`, "not valid YAML"},
	} {
		if _, err := ConfigSnippetEdits(tc.draft, tc.id, tc.params); err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("%s %s: %v", tc.id, tc.params, err)
		}
	}
}

func TestMTUSnippetAddsAMissingInterface(t *testing.T) {
	out, err := ConfigSnippetEdits(legacyDraft, "mtu", `{"interface":"eth0","mtu":"1400"}`)
	edited, _ := applySnippet(t, legacyDraft, out, err)

	if !strings.Contains(edited, "- interface: eth1\n              dhcp: true\n            - interface: eth0\n              mtu: 1400") {
		t.Errorf("edited:\n%s", edited)
	}
}

func TestDriftFixEdits(t *testing.T) {
	// NTP back to the reference's servers.
	out, err := DriftFixEdits(legacyDraft, "ntp", "a.example.test, b.example.test", "c.example.test")
	edited, r := applySnippet(t, legacyDraft, out, err)

	if !r.Fixable || !strings.Contains(edited, "- a.example.test\n            - b.example.test") {
		t.Errorf("ntp fix = %+v\n%s", r, edited)
	}

	// MTU: only the links that differ; a link the node lacks is left alone.
	noIfaces := strings.Replace(legacyDraft, "        interfaces:\n            - interface: eth1\n              dhcp: true\n", "", 1)
	out, err = DriftFixEdits(noIfaces, "mtu", "eth0=9000, eth1=9000, eth2=1500", "eth0=1500, eth1=1500, eth3=1500")
	edited, r = applySnippet(t, noIfaces, out, err)

	if len(r.Edits) != 1 || !strings.Contains(edited, "interface: eth0\n              mtu: 9000") ||
		!strings.Contains(edited, "interface: eth1\n              mtu: 9000") || strings.Contains(edited, "eth2") {
		t.Errorf("mtu fix = %+v\n%s", r.Edits, edited)
	}

	for _, tc := range []struct{ key, before, want string }{
		{"version", "v1.14.0", "upgrade the node"},
		{"extensions", "a=1", "installer image"},
		{"dns", "", "the reference has none"},
	} {
		out, err := DriftFixEdits(legacyDraft, tc.key, tc.before, "x")
		if r := decodeJSON[snippetResult](t, out, err); r.Fixable || !strings.Contains(r.Reason, tc.want) {
			t.Errorf("%s: %+v", tc.key, r)
		}
	}
}

func TestPutEditMakesTheObjectsOnTheWay(t *testing.T) {
	out, err := MachineConfigEdit(legacyDraft, `{"doc":0,"path":["machine","time","servers"],"op":"put","type":"yaml","value":"[\"a.example.test\"]"}`)
	if err != nil || !strings.Contains(out, "time:\n        servers:\n            - a.example.test") {
		t.Fatalf("put: %v\n%s", err, out)
	}

	// A hidden secret stays hidden.
	if _, err := MachineConfigEdit(legacyDraft, `{"doc":0,"path":["machine","token"],"op":"put","type":"yaml","value":"x"}`); err == nil ||
		!strings.Contains(err.Error(), "hidden secret") {
		t.Errorf("secret: %v", err)
	}

	// Into a scalar: refused.
	if _, err := MachineConfigEdit(legacyDraft, `{"doc":0,"path":["machine","type","x"],"op":"put","type":"yaml","value":"1"}`); err == nil {
		t.Error("a scalar has no fields")
	}
}
