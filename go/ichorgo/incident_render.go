package ichorgo

import (
	"fmt"
	"slices"
	"sort"
	"strings"
	"time"
)

const incidentTimeFormat = "2006-01-02 15:04:05Z"

func incidentTime(ms int64) string { return time.UnixMilli(ms).UTC().Format(incidentTimeFormat) }

// renderIncidentBounded renders v within limit bytes: the oldest timeline rows are dropped
// first, then the oldest actions, and what is still too long is cut.
func renderIncidentBounded(v incidentView, limit int) string {
	fits := func(dropEvents, dropActions int) bool {
		return len(renderIncident(v, dropEvents, dropActions)) <= limit
	}

	if fits(0, 0) {
		return renderIncident(v, 0, 0)
	}

	if fits(len(v.timeline), 0) {
		drop := sort.Search(len(v.timeline), func(i int) bool { return fits(i, 0) })

		return renderIncident(v, drop, 0)
	}

	drop := sort.Search(len(v.actions)+1, func(i int) bool { return fits(len(v.timeline), i) })

	return clipUTF8(renderIncident(v, len(v.timeline), drop), limit-len("…"))
}

func renderIncident(v incidentView, dropEvents, dropActions int) string {
	var b strings.Builder

	b.WriteString("# Incident summary: " + markdownCell(v.cluster) + "\n\n")
	writeIncidentNow(&b, v)
	writeIncidentTimeline(&b, v, dropEvents)
	writeIncidentActions(&b, v, dropActions)
	writeIncidentGaps(&b, v)

	fmt.Fprintf(&b, "---\n\nWindow: %s to %s (UTC). Generated by Ichor at %s (UTC), from what this phone recorded.\n",
		incidentTime(v.since), incidentTime(v.now), incidentTime(v.generated))

	return b.String()
}

func writeIncidentNow(b *strings.Builder, v incidentView) {
	b.WriteString("## What is wrong now\n\n")

	if !v.hasHistory {
		b.WriteString("No recorded history: this phone has not checked the cluster in the background yet.\n\n")

		return
	}

	if !v.lastReached {
		fmt.Fprintf(b, "At the last check (%s), this phone reached no node of the cluster.\n\n", incidentTime(v.lastAt))
	}

	if v.lastReachedAt == 0 {
		return
	}

	if len(v.wrongNodes) == 0 && len(v.openAlerts) == 0 {
		fmt.Fprintf(b, "Nothing: at the last check that reached the cluster (%s), every node was ready and no alert was open.\n\n",
			incidentTime(v.lastReachedAt))

		return
	}

	fmt.Fprintf(b, "At the last check that reached the cluster (%s):\n\n", incidentTime(v.lastReachedAt))

	for _, line := range slices.Concat(v.wrongNodes, v.openAlerts) {
		b.WriteString("- " + line + "\n")
	}

	b.WriteString("\n")
}

func writeIncidentTimeline(b *strings.Builder, v incidentView, drop int) {
	b.WriteString("## Timeline\n\n")

	switch {
	case !v.hasHistory:
		b.WriteString("Nothing recorded.\n\n")

		return
	case len(v.timeline) == 0:
		b.WriteString("No change recorded in this window.\n\n")

		return
	}

	if drop > 0 {
		fmt.Fprintf(b, "- … %d earlier events\n", drop)
	}

	for _, e := range v.timeline[drop:] {
		b.WriteString("- " + incidentTime(e.at) + " " + markdownCell(e.text) + "\n")
	}

	b.WriteString("\n")
}

func writeIncidentActions(b *strings.Builder, v incidentView, drop int) {
	b.WriteString("## Actions taken from the phone\n\n")

	if len(v.actions) == 0 {
		b.WriteString("No action was taken from this phone in this window.\n\n")

		return
	}

	if drop > 0 {
		fmt.Fprintf(b, "… %d earlier actions\n\n", drop)
	}

	b.WriteString("| Time (UTC) | Target | Action | Parameters | Outcome |\n")
	b.WriteString("|---|---|---|---|---|\n")

	for _, e := range v.actions[drop:] {
		action := e.Action
		if e.Demo {
			action += " (demo)"
		}

		outcome := e.Outcome
		if outcome == auditFailed {
			outcome = "**failed**"
		}

		if e.Error != "" {
			outcome += ": " + e.Error
		}

		cells := []string{incidentTime(e.At), e.Object, action, e.Params, outcome}
		for i, c := range cells {
			cells[i] = markdownCell(c)
		}

		b.WriteString("| " + strings.Join(cells, " | ") + " |\n")
	}

	b.WriteString("\n")
}

func writeIncidentGaps(b *strings.Builder, v incidentView) {
	b.WriteString("## Gaps\n\n")

	if !v.hasHistory || len(v.gaps) == 0 {
		if v.hasHistory {
			b.WriteString("None: this phone checked the cluster throughout the window.\n\n")
		} else {
			b.WriteString("The whole window: there is no record.\n\n")
		}

		return
	}

	b.WriteString("When this phone did not check the cluster (off its network, asleep): what happened then is not known, from this phone only.\n\n")

	for _, g := range v.gaps {
		fmt.Fprintf(b, "- %s to %s (%s)\n", incidentTime(g.From), incidentTime(g.To), incidentDuration(g.To-g.From))
	}

	b.WriteString("\n")
}

// incidentDuration is ms as "2d 3h", "3h 20m" or "45m".
func incidentDuration(ms int64) string {
	d := time.Duration(ms) * time.Millisecond
	days, hours, minutes := int(d/(24*time.Hour)), int(d%(24*time.Hour)/time.Hour), int(d%time.Hour/time.Minute)

	switch {
	case days > 0:
		return fmt.Sprintf("%dd %dh", days, hours)
	case hours > 0:
		return fmt.Sprintf("%dh %dm", hours, minutes)
	default:
		return fmt.Sprintf("%dm", max(minutes, 1))
	}
}
